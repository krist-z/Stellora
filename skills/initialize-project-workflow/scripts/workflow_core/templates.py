import re
from pathlib import Path, PurePosixPath

from .constants import (
    IMPORT_END_PREFIX,
    IMPORT_START_PREFIX,
    RUNTIME_VERSION,
    STATE_END,
    STATE_START,
    TEMPLATE_VERSION,
)
from .schema import pretty_json, read_text_preserve, sha256_file


IMPORT_BLOCK_RE = re.compile(
    r"<!-- workflow-imported-rules:start:(?P<name>[^>]+) -->\n"
    r"(?P<body>.*?)"
    r"<!-- workflow-imported-rules:end:(?P=name) -->",
    re.DOTALL,
)


def read_template(assets_root, relative):
    return read_text_preserve(Path(assets_root) / relative)


def render_template(assets_root, relative, replacements):
    text = read_template(assets_root, relative)
    for key, value in replacements.items():
        text = text.replace("{{" + key + "}}", value)
    return text


def imported_section(source_name, content):
    if content is None or content == "":
        return ""
    ending = "" if content.endswith(("\n", "\r")) else "\n"
    return (
        "\n## Imported Existing Rules\n\n"
        f"Source: `{source_name}`\n\n"
        f"{IMPORT_START_PREFIX}{source_name} -->\n"
        f"{content}{ending}"
        f"{IMPORT_END_PREFIX}{source_name} -->\n"
    )


def extract_imported_sections(text):
    if not text:
        return {}
    return {match.group("name"): match.group("body") for match in IMPORT_BLOCK_RE.finditer(text)}


