def render_project(scan, mode):
    lines = [
        "# Project Facts", "", "Generated by initialize-project-workflow from local files.", "",
        f"- Mode: {mode}", f"- Git repository: {'yes' if scan['is_git'] else 'no'}",
        "- Acceptance coverage: \u672a\u53d1\u73b0/\u672a\u9a8c\u8bc1", "",
        "## Discovered Commands", "",
    ]
    if scan.get("commands"):
        for name, value in scan["commands"].items():
            if isinstance(value, dict) and value.get("command"):
                lines.append(f"- `{name}`: `{value['command']}` (evidence: `{value.get('evidence', '未发现/未验证')}`)")
            else:
                evidence = value.get("evidence", "未发现/未验证") if isinstance(value, dict) else value
                lines.append(f"- `{name}`: 未发现/未验证 (evidence: `{evidence}`)")
    else:
        lines.append("- \u672a\u53d1\u73b0/\u672a\u9a8c\u8bc1")
    lines.extend(["", "- Sensitive-file patterns: `*.env`, `*.pem`, `*.key`, `*token*`, `*secret*`", "", "## Deterministic File Scan", ""])
    for category in ("manifests", "readmes", "source", "tests", "scripts"):
        files = scan["files"][category]
        lines.append(f"### {category.title()}")
        if files:
            for rel in files:
                digest = scan["file_hashes"][rel][:12]
                lines.append(f"- `{rel}` sha256:{digest}")
        else:
            lines.append("- (none)")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def template_hashes(assets_root):
    root = Path(assets_root)
    hashes = {}
    if not root.exists():
        return hashes
    for path in sorted(root.rglob("*"), key=lambda item: item.relative_to(root).as_posix().lower()):
        if path.is_file():
            rel = path.relative_to(root).as_posix()
            if ".." in PurePosixPath(rel).parts:
                raise ValueError(f"template path escapes root: {rel}")
            hashes[rel] = sha256_file(path)
    return hashes
